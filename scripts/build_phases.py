def check_timeline(timeline, tag: str) -> None:
    prev_end = None
    for ph in timeline:
        s, e = date.fromisoformat(ph["start"]), date.fromisoformat(ph["end"])
        span = (e - s).days + 1
        if span != ph["weeks"] * 7:
            raise SystemExit(f"[x] {tag} {ph['id']} 周数与日期不符：{span} 天 ≠ {ph['weeks']} 周")
        if prev_end and s != prev_end + timedelta(days=1):
            raise SystemExit(f"[x] {tag} {ph['id']} 与上一阶段不连续")
        prev_end = e


def apply(path: Path, cfg: dict, timeline) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    data["title"] = cfg["title"]
    data["examDate"] = EXAM_DATE
    data["yearGoal"] = cfg["yearGoal"]

    phases = []
    for meta in timeline:
        body = cfg["phases"][meta["id"]]
        if sum(b["weeks"] for b in body["blocks"]) != meta["weeks"]:
            raise SystemExit(f"[x] {path.name} {meta['id']} 周骨架合计 ≠ {meta['weeks']} 周")
        ph = dict(meta)
        ph.update(body)
        phases.append(ph)
    data["phases"] = phases

    # 每条周计划挂上所属阶段（按周起始日期判断）
    start = date.fromisoformat(data["startDate"])
    for w in data["weeks"]:
        wk_start = start + timedelta(days=7 * (w["week"] - 1))
        hit = None
        for ph in phases:
            if date.fromisoformat(ph["start"]) <= wk_start <= date.fromisoformat(ph["end"]):
                hit = ph["id"]
                break
        if not hit:
            raise SystemExit(f"[x] {path.name} 第 {w['week']} 周 {wk_start} 不在任何阶段内")
        w["phase"] = hit

    path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"  + {path.name}：{len(phases)} 个阶段 / "
          f"{sum(p['weeks'] for p in phases)} 周 / 细化周 {len(data['weeks'])} 个")


def main() -> int:
    print(f"主线时间线：{TIMELINE[0]['start']} → {TIMELINE[-1]['end']}，初试 {EXAM_DATE}")
    print(f"政治时间线：{POLITICS_TIMELINE[0]['start']} → {POLITICS_TIMELINE[-1]['end']}")
    for name, (cfg, timeline) in SUBJECTS.items():
        check_timeline(timeline, name)
        p = DATA / name
        if not p.exists():
            print(f"[x] 缺少 {name}", file=sys.stderr)
            return 1
        apply(p, cfg, timeline)
    return 0


